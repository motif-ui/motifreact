import type {
  Dimension,
  FigmaAlias,
  FigmaEffectStyle,
  FigmaPayload,
  FigmaTextStyle,
  FigmaValue,
  FigmaVariable,
  Shadow,
  Token,
} from "./types.ts";

const ALIAS = /^\{(.+)\}$/;

// Narrows to the alias shape only, so a non-alias string keeps its string type
export const isAlias = (value: unknown): value is `{${string}}` => typeof value === "string" && ALIAS.test(value);
export const aliasPath = (value: string) => (value.match(ALIAS)?.[1] ?? "").split(".");
export const cssName = (path: string[]) => `--mtf-${path.join("-")}`;
export const figmaName = (path: string[]) => path.join("/");

// --- DTCG ---

type DtcgToken = { $type: string; $value: unknown; $description?: string; $extensions?: { "com.motif.modes": { dark: string } } };
type DtcgGroup = { [key: string]: DtcgGroup | DtcgToken };

const dtcgToken = ({ type, value, dark, description }: Token) => ({
  $type: type,
  $value: value,
  ...(description && { $description: description }),
  ...(dark && { $extensions: { "com.motif.modes": { dark } } }),
});

/** Nested DTCG tree. The light value is `$value`; a differing dark value sits in `$extensions["com.motif.modes"].dark`. */
export const toDtcg = (tokens: Token[]) =>
  tokens.reduce<DtcgGroup>((root, token) => {
    const group = token.path.slice(0, -1).reduce((parent, key) => (parent[key] ??= {}) as DtcgGroup, root);
    group[token.path[token.path.length - 1]] = dtcgToken(token);
    return root;
  }, {});

// --- CSS ---

const cssDimension = ({ value, unit }: Dimension) =>
  value === 0 ? "0" : unit === "px" ? `${+(value / 16).toFixed(4)}rem` : `${value}${unit}`;

const cssValue = (value: Token["value"]) =>
  isAlias(value) ? `var(${cssName(aliasPath(value))})` : typeof value === "object" ? cssDimension(value as Dimension) : String(value);

const cssShadow = ({ offsetX, offsetY, blur, spread, color }: Shadow) =>
  [offsetX, offsetY, blur, spread].map(cssDimension).concat(cssValue(color)).join(" ");

const cssDeclaration = (token: Token) =>
  `  ${cssName(token.path)}: ${token.type === "shadow" ? cssShadow(token.value) : token.dark ? `light-dark(${cssValue(token.value)}, ${cssValue(token.dark)})` : cssValue(token.value)};`;

const MODE_RULES = [
  '[data-mtf-mode="dark"] { color-scheme: dark; }',
  '[data-mtf-mode="system"] { color-scheme: light dark; }',
  '[data-mtf-surface="opposite"] { color-scheme: dark; }',
  '[data-mtf-mode="dark"] [data-mtf-surface="opposite"] { color-scheme: light; }',
];

export const toCss = (tokens: Token[]) =>
  [
    "/* Motif UI theme tokens. Generated by src/scripts/tokens, do not edit by hand. */",
    ":root {",
    "  color-scheme: light;",
    ...tokens.map(cssDeclaration),
    "}",
    "",
    ...MODE_RULES,
    "",
  ].join("\n");

// --- Figma ---

export const FIGMA_SCOPES = [
  "ALL_SCOPES",
  "TEXT_CONTENT",
  "CORNER_RADIUS",
  "WIDTH_HEIGHT",
  "GAP",
  "ALL_FILLS",
  "FRAME_FILL",
  "SHAPE_FILL",
  "TEXT_FILL",
  "STROKE_COLOR",
  "STROKE_FLOAT",
  "EFFECT_FLOAT",
  "EFFECT_COLOR",
  "OPACITY",
  "FONT_FAMILY",
  "FONT_STYLE",
  "FONT_WEIGHT",
  "FONT_SIZE",
  "LINE_HEIGHT",
  "LETTER_SPACING",
  "PARAGRAPH_SPACING",
  "PARAGRAPH_INDENT",
];

// First match wins. An empty list hides the variable from every picker.
const SCOPE_RULES: [RegExp, string[]][] = [
  [/^color\/(palette|seed)\//, []],
  [/^elevation\//, ["EFFECT_COLOR"]],
  [/^color\/text\//, ["TEXT_FILL", "SHAPE_FILL"]],
  [/^color\/border\//, ["STROKE_COLOR"]],
  [/^color\/focus-ring$/, ["STROKE_COLOR", "EFFECT_COLOR"]],
  [/^color\/on-/, ["TEXT_FILL", "SHAPE_FILL", "STROKE_COLOR"]],
  [/^color\/[a-z]+\/text$/, ["TEXT_FILL", "SHAPE_FILL"]],
  [/^color\/[a-z]+\/border(-soft)?$/, ["STROKE_COLOR"]],
  [/^color\//, ["FRAME_FILL", "SHAPE_FILL"]],
  [/^sizing\/radius\//, ["CORNER_RADIUS"]],
  [/^sizing\/container\//, ["WIDTH_HEIGHT"]],
  [/^sizing\/space\//, ["GAP"]],
  [/^sizing\//, ["WIDTH_HEIGHT"]],
  [/^typography\/weight\//, ["FONT_WEIGHT"]],
  [/\/font-weight$/, ["FONT_WEIGHT"]],
  [/\/font-size$/, ["FONT_SIZE"]],
  [/\/line-height$/, ["LINE_HEIGHT"]],
  [/^typography\/font-family$/, ["FONT_FAMILY"]],
];

// CSS-only tokens: font stacks with generic families have no Figma equivalent
const FIGMA_EXCLUDED = ["typography/font-family-mono"];

const scopesOf = (name: string) => SCOPE_RULES.find(([pattern]) => pattern.test(name))?.[1] ?? [];

const COLLECTION_MODES = { Palette: ["Value"], Semantic: ["Light", "Dark"], Dimension: ["Value"] };

type Collection = keyof typeof COLLECTION_MODES;

const collectionOf = ({ path, type }: Token) =>
  path[0] === "color" && ["palette", "seed"].includes(path[1]) ? "Palette" : type === "color" ? "Semantic" : "Dimension";

const figmaDimension = ({ value, unit }: Dimension) => +(unit === "rem" ? value * 16 : value).toFixed(4);

const figmaValue = (type: Token["type"], value: Token["value"]): FigmaValue =>
  isAlias(value)
    ? { alias: figmaName(aliasPath(value)) }
    : type === "dimension"
      ? figmaDimension(value as Dimension)
      : type === "fontFamily" && typeof value === "string"
        ? value.split(",")[0].replaceAll('"', "").trim()
        : (value as string | number);

const FIGMA_TYPES: Record<Exclude<Token["type"], "shadow">, FigmaVariable["type"]> = {
  color: "COLOR",
  dimension: "FLOAT",
  fontWeight: "FLOAT",
  fontFamily: "STRING",
};

const figmaVariable = (token: Token) => {
  const { path, type, value, dark, description } = token;
  const name = figmaName(path);
  const [lightMode, darkMode] = COLLECTION_MODES[collectionOf(token)];
  const scopes = scopesOf(name);
  return {
    name,
    type: FIGMA_TYPES[type as Exclude<Token["type"], "shadow">],
    scopes,
    hiddenFromPublishing: scopes.length === 0 || name.startsWith("elevation/"),
    ...(description && { description }),
    values: {
      [lightMode]: figmaValue(type, value),
      ...(darkMode && { [darkMode]: figmaValue(type, dark ?? value) }),
    },
  };
};

const effectStyle = ({ path, value, description }: Token): FigmaEffectStyle => {
  const { offsetX, offsetY, blur, spread, color } = value as Shadow;
  return {
    name: figmaName(path),
    ...(description && { description }),
    effects: [
      {
        type: "DROP_SHADOW",
        offset: { x: offsetX.value, y: offsetY.value },
        radius: blur.value,
        spread: spread.value,
        color: figmaValue("color", color) as FigmaAlias,
      },
    ],
  };
};

// One text style per type role, every property bound to its variable
const TEXT_STYLE_PROPERTIES = { fontSize: "font-size", lineHeight: "line-height", fontWeight: "font-weight" };

const textStyle = (role: string): FigmaTextStyle => ({
  name: `typography/${role}`,
  fontFamily: { alias: "typography/font-family" },
  fontSize: { alias: `typography/${role}/${TEXT_STYLE_PROPERTIES.fontSize}` },
  lineHeight: { alias: `typography/${role}/${TEXT_STYLE_PROPERTIES.lineHeight}` },
  fontWeight: { alias: `typography/${role}/${TEXT_STYLE_PROPERTIES.fontWeight}` },
});

/**
 * Payload for the Figma sync: variable collections with their modes, plus effect and text styles. Colors stay hex, aliases are
 * `{ alias: "<variable name>" }`, dimensions are px numbers (Figma variables have no units).
 */
export const toFigma = (tokens: Token[]): FigmaPayload => {
  const variables = tokens.filter(({ type, path }) => type !== "shadow" && !FIGMA_EXCLUDED.includes(figmaName(path)));
  return {
    collections: (Object.entries(COLLECTION_MODES) as [Collection, string[]][]).map(([name, modes]) => ({
      name,
      modes,
      variables: variables.filter(token => collectionOf(token) === name).map(figmaVariable),
    })),
    effectStyles: tokens.filter(({ type }) => type === "shadow").map(effectStyle),
    textStyles: tokens
      .filter(({ path }) => path[0] === "typography" && path[path.length - 1] === "font-size")
      .map(({ path }) => textStyle(path[1])),
  };
};
